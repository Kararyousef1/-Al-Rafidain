// ── Course Viewer ─────────────────────────────────────────────────────────────
const CourseViewer = ({
  course,
  onBack,
  onCertificate,
}: {
  course: Course;
  onBack: () => void;
  onCertificate: (course: Course) => void;
}) => {
  const [activeModuleIdx, setActiveModuleIdx] = useState(0);
  const [completedModules, setCompletedModules] = useState<Set<string>>(
    new Set(course.moduleList.filter(m => m.completed).map(m => m.id))
  );
  const [quizMode, setQuizMode] = useState(false);
  const [sidebarOpen, setSidebarOpen] = useState(true);

  const activeModule = course.moduleList[activeModuleIdx];
  const progress = Math.round((completedModules.size / course.moduleList.length) * 100);
  const catData = CATEGORIES.find(c => c.id === course.category);
  const Icon = catData?.icon ?? BookOpen;

  if (!activeModule) return null;

  const handleMarkComplete = () => {
    const newSet = new Set(completedModules);
    newSet.add(activeModule.id);
    setCompletedModules(newSet);
    if (activeModuleIdx < course.moduleList.length - 1) {
      setActiveModuleIdx(activeModuleIdx + 1);
    }
  };

  const handleQuizComplete = (score: number) => {
    if (score >= 80) { // يجب اجتياز 80% لفتح الوحدة التالية
      const newSet = new Set(completedModules);
      newSet.add(activeModule.id);
      setCompletedModules(newSet);
    }
    setQuizMode(false);
  };

  const allDone = completedModules.size === course.moduleList.length;

  const renderContent = (content: string) => {
    return content.split('\n').map((line, i) => {
      if (line.startsWith('**') && line.endsWith('**')) {
        return <h3 key={i} className="font-bold text-slate-800 text-base mt-4 mb-2">{line.slice(2, -2)}</h3>;
      }
      if (line.startsWith('- ')) {
        return <li key={i} className="text-slate-600 text-sm leading-relaxed mr-4">{line.slice(2)}</li>;
      }
      if (line.match(/^\d+\. /)) {
        const text = line.replace(/^\d+\. /, '');
        const match = text.match(/\*\*(.*?)\*\*(.*)/);
        if (match) {
          return (
            <div key={i} className="flex gap-2 mb-1">
              <span className="text-slate-400 text-sm font-mono">{line.match(/^\d+/)?.[0]}.</span>
              <p className="text-slate-600 text-sm leading-relaxed">
                <strong className="text-slate-800">{match[1]}</strong>{match[2]}
              </p>
            </div>
          );
        }
        return <p key={i} className="text-slate-600 text-sm leading-relaxed">{line}</p>;
      }
      if (line.includes('**')) {
        const parts = line.split(/\*\*(.*?)\*\*/g);
        return (
          <p key={i} className="text-slate-600 text-sm leading-relaxed mb-1">
            {parts.map((part, j) => j % 2 === 1 ? <strong key={j} className="text-slate-800 font-semibold">{part}</strong> : part)}
          </p>
        );
      }
      if (line === '' || line === '---') return <div key={i} className={line === '---' ? 'border-t border-slate-100 my-4' : 'mb-2'} />;
      return <p key={i} className="text-slate-600 text-sm leading-relaxed mb-1">{line}</p>;
    });
  };

  return (
    <div className="flex flex-col h-screen bg-slate-50 -m-4 sm:-m-6" dir="rtl">
      {/* Top Bar */}
      <div className="bg-white border-b border-slate-200 px-4 py-3 flex items-center gap-3 flex-shrink-0">
        <button onClick={onBack} className="flex items-center gap-2 text-slate-500 hover:text-slate-800 transition-colors text-sm font-medium">
          <Home size={16}/> العودة للفهرس
        </button>
        <ChevronLeft size={14} className="text-slate-300" />
        <div className="flex items-center gap-2 flex-1 min-w-0">
          <div className={`w-7 h-7 rounded-lg bg-gradient-to-br ${catData?.color} flex items-center justify-center flex-shrink-0`}>
            <Icon size={14} className="text-white" />
          </div>
          <span className="text-slate-700 font-semibold text-sm truncate">{course.title}</span>
        </div>
        {/* Progress */}
        <div className="hidden sm:flex items-center gap-2 flex-shrink-0">
          <div className="w-24 h-1.5 bg-slate-100 rounded-full overflow-hidden">
            <div className="h-full bg-gradient-to-r from-indigo-400 to-indigo-600 rounded-full transition-all duration-500"
              style={{ width: `${progress}%` }} />
          </div>
          <span className="text-xs font-bold text-indigo-600">{progress}%</span>
        </div>
        <button onClick={() => setSidebarOpen(!sidebarOpen)}
          className="p-1.5 rounded-lg bg-slate-100 text-slate-500 hover:bg-slate-200 transition-colors flex-shrink-0">
          <List size={16} />
        </button>
      </div>

      <div className="flex flex-1 overflow-hidden relative">
        {/* Mobile Sidebar Backdrop */}
        {sidebarOpen && (
          <div className="md:hidden fixed inset-0 z-[40] bg-slate-900/50 backdrop-blur-sm" onClick={() => setSidebarOpen(false)} />
        )}
        {/* Sidebar */}
        {sidebarOpen && (
          <div className="absolute right-0 md:relative z-[50] h-full w-72 bg-white border-l border-slate-200 flex flex-col overflow-hidden flex-shrink-0 shadow-2xl md:shadow-none transition-transform">
            <div className="p-4 border-b border-slate-100">
              <div className="flex items-center justify-between mb-2">
                <h3 className="font-bold text-slate-800 text-sm">محتوى الدورة</h3>
                <span className="text-xs text-slate-400">{completedModules.size}/{course.moduleList.length}</span>
              </div>
              <div className="h-1.5 bg-slate-100 rounded-full overflow-hidden">
                <div className="h-full bg-gradient-to-r from-indigo-400 to-indigo-600 rounded-full transition-all"
                  style={{ width: `${progress}%` }} />
              </div>
            </div>
            <div className="flex-1 overflow-y-auto">
              {course.moduleList.map((mod, idx) => {
                const TypeIcon = MODULE_TYPE_ICON[mod.type];
                const isActive = idx === activeModuleIdx;
                const isDone = completedModules.has(mod.id);
                const isLocked = idx > 0 && !completedModules.has(course.moduleList[idx - 1].id);
                return (
                  <button
                    key={mod.id}
                    onClick={() => !isLocked && setActiveModuleIdx(idx)}
                    disabled={isLocked}
                    className={`w-full text-right p-3 border-b border-slate-50 flex items-start gap-3 transition-all
                      ${isActive ? 'bg-indigo-50 border-r-2 border-r-indigo-500' : ''}
                      ${isLocked ? 'opacity-40 cursor-not-allowed' : 'hover:bg-slate-50 cursor-pointer'}`}
                  >
                    <div className={`w-7 h-7 rounded-lg flex items-center justify-center flex-shrink-0 mt-0.5
                      ${isDone ? 'bg-emerald-100' : isActive ? 'bg-indigo-100' : 'bg-slate-100'}`}>
                      {isDone ? <CheckCircle size={14} className="text-emerald-600" /> : <TypeIcon size={14} className={isActive ? 'text-indigo-600' : 'text-slate-400'} />}
                    </div>
                    <div className="flex-1 min-w-0">
                      <p className={`text-xs font-semibold leading-snug mb-0.5 ${isActive ? 'text-indigo-700' : 'text-slate-700'}`}>
                        {idx + 1}. {mod.title}
                      </p>
                      <div className="flex items-center gap-2">
                        <span className="text-[10px] text-slate-400">{MODULE_TYPE_LABEL[mod.type]}</span>
                        <span className="text-[10px] text-slate-400">•</span>
                        <span className="text-[10px] text-slate-400">{mod.duration}</span>
                      </div>
                    </div>
                  </button>
                );
              })}
            </div>

            {/* All Done */}
            {allDone && (
              <div className="p-4 border-t border-slate-100">
                <button
                  onClick={() => onCertificate(course)}
                  className="w-full py-2.5 rounded-xl bg-gradient-to-r from-amber-400 to-amber-600 text-white font-bold text-sm hover:shadow-md transition-all flex items-center justify-center gap-2"
                >
                  <Award size={16} /> احصل على شهادتك
                </button>
              </div>
            )}
          </div>
        )}

        {/* Main Content */}
        <div className="flex-1 overflow-y-auto">
          <div className="max-w-3xl mx-auto p-6">
            {/* Module Header */}
            <div className="mb-6">
              <div className="flex items-center gap-2 mb-2">
                <span className={`text-[10px] font-bold px-2 py-0.5 rounded-full bg-indigo-100 text-indigo-700`}>
                  {MODULE_TYPE_LABEL[activeModule.type]}
                </span>
                <span className="text-[10px] text-slate-400 flex items-center gap-1">
                  <Timer size={10} /> {activeModule.duration}
                </span>
              </div>
              <h1 className="text-xl font-extrabold text-slate-800 mb-1">{activeModule.title}</h1>
              <p className="text-sm text-slate-400">{course.instructor}</p>
            </div>

            {/* Content */}
            {quizMode && activeModule.quiz ? (
              <div className="bg-white rounded-2xl border border-slate-200 p-6">
                <QuizView module={activeModule} onComplete={handleQuizComplete} onBack={() => setQuizMode(false)} />
              </div>
            ) : (
              <>
                {/* Reading/Practical Content */}
                {activeModule.type !== 'quiz' ? (
                  <div className="bg-white rounded-2xl border border-slate-200 p-6 mb-5">
                    <div className="prose prose-slate max-w-none">
                      {renderContent(activeModule.content)}
                    </div>
                  </div>
                ) : (
                  <div className="bg-gradient-to-br from-indigo-50 to-violet-50 border border-indigo-100 rounded-2xl p-6 mb-5 text-center">
                    <div className="w-16 h-16 mx-auto mb-3 bg-indigo-100 rounded-2xl flex items-center justify-center">
                      <HelpCircle size={28} className="text-indigo-600" />
                    </div>
                    <h3 className="font-bold text-slate-800 mb-1">{activeModule.title}</h3>
                    <p className="text-slate-500 text-sm mb-4">{activeModule.content}</p>
                    <p className="text-xs text-indigo-600 font-semibold mb-4">
                      {activeModule.quiz?.length} سؤال • 80% للنجاح الصارم • {activeModule.duration}
                    </p>
                    {completedModules.has(activeModule.id) ? (
                      <div className="inline-flex items-center gap-2 bg-emerald-100 text-emerald-700 px-4 py-2 rounded-xl font-bold text-sm">
                        <CheckCircle size={16} /> تم الاجتياز بنجاح
                      </div>
                    ) : (
                      <button
                        onClick={() => setQuizMode(true)}
                        className="inline-flex items-center gap-2 bg-indigo-600 text-white px-6 py-2.5 rounded-xl font-bold text-sm hover:bg-indigo-700 transition-colors"
                      >
                        <Play size={14} /> ابدأ الاختبار
                      </button>
                    )}
                  </div>
                )}

                {/* Key Points */}
                {activeModule.keyPoints.length > 0 && (
                  <div className="bg-amber-50 border border-amber-200 rounded-2xl p-5 mb-5">
                    <h4 className="font-bold text-amber-800 text-sm mb-3 flex items-center gap-2">
                      <Star size={14} className="fill-amber-500 text-amber-500" /> النقاط الجوهرية
                    </h4>
                    <ul className="space-y-2">
                      {activeModule.keyPoints.map((kp, i) => (
                        <li key={i} className="flex items-start gap-2 text-sm text-amber-700">
                          <CheckCircle size={14} className="text-amber-500 flex-shrink-0 mt-0.5" />
                          {kp}
                        </li>
                      ))}
                    </ul>
                  </div>
                )}

                {/* Navigation */}
                <div className="flex gap-3">
                  {activeModuleIdx > 0 && (
                    <button onClick={() => setActiveModuleIdx(activeModuleIdx - 1)}
                      className="flex items-center gap-2 px-4 py-2.5 rounded-xl bg-slate-100 text-slate-600 font-semibold text-sm hover:bg-slate-200 transition-colors">
                      <ChevronRight size={14} /> السابق
                    </button>
                  )}
                  <div className="flex-1" />
                  {activeModule.type === 'quiz' && !completedModules.has(activeModule.id) ? (
                    <button onClick={() => setQuizMode(true)}
                      className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-indigo-600 text-white font-bold text-sm hover:bg-indigo-700 transition-colors">
                      <Play size={14} /> ابدأ الاختبار
                    </button>
                  ) : completedModules.has(activeModule.id) ? (
                    activeModuleIdx < course.moduleList.length - 1 ? (
                      <button onClick={() => setActiveModuleIdx(activeModuleIdx + 1)}
                        className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-indigo-600 text-white font-bold text-sm hover:bg-indigo-700 transition-colors">
                        التالي <ChevronLeft size={14} />
                      </button>
                    ) : (
                      <button onClick={() => onCertificate(course)}
                        className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-gradient-to-r from-amber-400 to-amber-600 text-white font-bold text-sm hover:shadow-md transition-all">
                        <Award size={14} /> احصل على الشهادة
                      </button>
                    )
                  ) : (
                    <button onClick={handleMarkComplete}
                      className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-emerald-600 text-white font-bold text-sm hover:bg-emerald-700 transition-colors">
                      <CheckCircle size={14} /> تم القراءة — التالي
                    </button>
                  )}
                </div>
              </>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};

